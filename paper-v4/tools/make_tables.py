# Dates in US format, with the IEEE month abbreviations.
MONTHS = ["Jan.", "Feb.", "Mar.", "Apr.", "May", "Jun.", "Jul.", "Aug.", "Sept.", "Oct.", "Nov.", "Dec."]


def check_input(key, word):
    """The input family written in a cell must agree with the script line recorded in recomputed.json."""
    text = INPUTS[key][0]
    ok = ("fixed" in text) if word == "fixed" else ("alphabet" in text)
    if not ok:
        raise SystemExit(f"input of {key!r} is {text!r}, not {word}")
    return word


def dec(x, d):
    """A recorded time with the d decimals that its script rounds to. Stops if the record has more decimals."""
    if abs(round(x, d) - x) > 1e-12:
        raise SystemExit(f"{x} has more than {d} decimals")
    return f"{x:.{d}f}"


def hdr(a, b, align="c"):
    """A header on two lines."""
    return f"\\begin{{tabular}}[b]{{@{{}}{align}@{{}}}}{a}\\\\{b}\\end{{tabular}}"


def tabular(spec, header, rows, name, role, pre=None, full=False):
    """full=True sets a tabular* as wide as the line (\\linewidth: the text in table*, the column in table), with
    the extra space spread between the columns by \\extracolsep{\\fill}. Font size and content do not change."""
    lines = [f"% {name}: {role}. Generated by paper-v4/tools/make_tables.py; do not edit.",
             (f"\\begin{{tabular*}}{{\\linewidth}}{{@{{\\extracolsep{{\\fill}}}}{spec[3:]}}}" if full
              else f"\\begin{{tabular}}{{{spec}}}"), "\\toprule"]
    if pre:
        lines.append(pre)
    lines += [" & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MID" else " & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular*}%" if full else "\\end{tabular}%", ""]
    write(OUT / f"{name}.tex", "\n".join(lines))


def note(name, text):
    write(OUT / f"{name}_note.tex", f"% {name}, note. Generated by paper-v4/tools/make_tables.py; do not edit.\n{text}\n")


def date_utc(epoch_key):
    """'2026-08-08T04:50:06Z' -> 'Aug. 8, 2026, 04:50'"""
    s = rv(epoch_key)
    y, m, d = s[:10].split("-")
    return f"{MONTHS[int(m) - 1]} {int(d)}, {y}, {s[11:16]}"


def date_day(iso):
    y, m, d = iso.split("-")
    return f"{MONTHS[int(m) - 1]} {int(d)}, {y}"


