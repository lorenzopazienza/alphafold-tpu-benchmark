def runs(rows_, key):
    """Runs per setting, counted from the data file: every setting must appear the same number of times."""
    from collections import Counter
    c = Counter(r[key] for r in rows_)
    if len(set(c.values())) != 1:
        raise SystemExit(f"uneven runs per setting for {key}: {c}")
    return str(next(iter(c.values())))


