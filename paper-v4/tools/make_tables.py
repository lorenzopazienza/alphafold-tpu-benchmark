"""Tables I to V of the paper, written to paper-v4/tables/ as booktabs tabulars with a note file each.

Every value is read from the committed data files (results/) or from paper-v4/analysis/out/recomputed.json. The
generator only formats them. Words in the cells (script, input, timed region) are checked against the script lines
recorded in recomputed.json (INPUT.per_experiment, TIMED.region) before they are written.

Times keep the decimals that the scripts round to (src/spike_*_forward_pass.py: init_params and the first call to
two decimals; the steady-state call to three decimals in the single-query and partitioning scripts and to four in
the vmap, pmap, and ensemble scripts), including trailing zeros. dec() stops if a value has more decimals.

    python3 paper-v4/tools/make_tables.py
"""
