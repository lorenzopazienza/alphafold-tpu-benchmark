def check_input(key, word):
    """The input family written in a cell must agree with the script line recorded in recomputed.json."""
    text = INPUTS[key][0]
    ok = ("fixed" in text) if word == "fixed" else ("alphabet" in text)
    if not ok:
        raise SystemExit(f"input of {key!r} is {text!r}, not {word}")
    return word


def hdr(a, b, align="c"):
    """A header on two lines."""
    return f"\\begin{{tabular}}[b]{{@{{}}{align}@{{}}}}{a}\\\\{b}\\end{{tabular}}"


def tabular(spec, header, rows, name, role):
    lines = [f"% {name}: {role}. Generated by paper-v3/tools/make_tables.py; do not edit.",
             f"\\begin{{tabular}}{{{spec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MID" else " & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}%", ""]
    write(OUT / f"{name}.tex", "\n".join(lines))


def note(name, text):
    write(OUT / f"{name}_note.tex", f"% {name}, note. Generated by paper-v3/tools/make_tables.py; do not edit.\n{text}\n")


def date_utc(epoch_key):
    """'2026-08-08T04:50:06Z' -> '8 Aug 2026, 04:50'"""
    s = rv(epoch_key)
    months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    y, m, d = s[:10].split("-")
    return f"{int(d)} {months[int(m) - 1]} {y}, {s[11:16]}"


def date_day(iso):
    months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    y, m, d = iso.split("-")
    return f"{int(d)} {months[int(m) - 1]} {y}"


