"""Tables I to IV of the paper, written to paper-v3/tables/ as booktabs tabulars with a note file each.

Every value is read from the committed data files (results/) or from paper-v3/analysis/out/recomputed.json. The
generator only formats them. Words in the cells (script, input, timed region) are checked against the script lines
recorded in recomputed.json (INPUT.per_experiment, TIMED.region) before they are written.

    python3 paper-v3/tools/make_tables.py
"""
